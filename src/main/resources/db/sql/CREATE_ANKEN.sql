CREATE TABLE IF NOT EXISTS ANKEN (
    ANKEN_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ACCNT_ID INT,
    ANKEN_NAME VARCHAR(256),
    DESCRIPTION VARCHAR(8192),
    WORK_PLACE VARCHAR(256),
    TERM VARCHAR(256),
    AGE VARCHAR(256),
    BILLING_RATE VARCHAR(256),
    MIN_RATE_NUM INT,
    MAX_RATE_NUM INT,
    RECRUIT_NUM INT,
    STATUS INT,
    VERSION INT,
    IS_DELETED INT,
    CREATED_BY VARCHAR(128),
    CREATED_AT DATETIME,
    UPDATED_BY VARCHAR(128),
    UPDATED_AT TIMESTAMP
);
